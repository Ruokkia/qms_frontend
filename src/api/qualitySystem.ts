import { apiGet, apiPost, apiPut } from './request'
export const getQualityDashboard=()=>apiGet<Record<string,any>>('/quality-system/dashboard')
export const getObjectives=()=>apiGet<any[]>('/quality-system/objectives')
export const createObjective=(data:any)=>apiPost('/quality-system/objectives',data)
export const updateObjective=(id:number,data:any)=>apiPut(`/quality-system/objectives/${id}`,data)
export const getAudits=()=>apiGet<any[]>('/quality-system/audits')
export const createAudit=(data:any)=>apiPost('/quality-system/audits',data)
export const updateAudit=(id:number,data:any)=>apiPut(`/quality-system/audits/${id}`,data)
export const transitionAudit=(id:number,status:string,data?:any)=>apiPost(`/quality-system/audits/${id}/transition`,data,{params:{status}})
export const getNonconformities=()=>apiGet<any[]>('/quality-system/nonconformities')
export const createNonconformity=(data:any)=>apiPost('/quality-system/nonconformities',data)
export const updateNonconformity=(id:number,data:any)=>apiPut(`/quality-system/nonconformities/${id}`,data)
export const closeNonconformity=(id:number,data:any)=>apiPost(`/quality-system/nonconformities/${id}/close`,data)
export const getEvents=()=>apiGet<any[]>('/quality-system/events')
export const createEvent=(data:any)=>apiPost('/quality-system/events',data)
export const updateEvent=(id:number,data:any)=>apiPut(`/quality-system/events/${id}`,data)
export const getFeedback=()=>apiGet<any[]>('/quality-system/feedback')
export const createFeedback=(data:any)=>apiPost('/quality-system/feedback',data)
export const updateFeedback=(id:number,data:any)=>apiPut(`/quality-system/feedback/${id}`,data)
export const closeFeedback=(id:number,data:any)=>apiPost(`/quality-system/feedback/${id}/close`,data)
export const createQualityCapa=(kind:'nonconformities'|'events'|'feedback',id:number)=>apiPost<{exceptionId:number;capaNo:string}>(`/quality-system/${kind}/${id}/capa`)
